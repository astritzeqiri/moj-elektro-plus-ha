const STRINGS = { en, sl };

export function language(hass) {
  const lang = (hass?.locale?.language || hass?.language || "en").toLowerCase();
  return lang.startsWith("sl") ? "sl" : "en";
}

export function translator(lang) {
  const table = STRINGS[lang] || en;
  return (key, vars = {}) => {
    const value = key.split(".").reduce((obj, part) => obj?.[part], table) ??
      key.split(".").reduce((obj, part) => obj?.[part], en) ?? key;
    return String(value).replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
  };
}

export { STRINGS };
